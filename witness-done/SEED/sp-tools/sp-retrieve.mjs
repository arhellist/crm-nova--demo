#!/usr/bin/env node
/**
 * sp-retrieve — Context Pack index / validate / draft
 * Witness Done | правило с v1.9 | catalogs/context-rag.md
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveProjectRoot } from './evidence-lib.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function parseArgs(argv) {
  const out = {
    reindex: false,
    validate: false,
    d: null,
    pack: null,
    query: null,
    out: null,
    root: process.cwd(),
    rootGiven: false,
    factory: null,
    help: false,
    maxChunks: 12,
    maxChunksGiven: false,
  };
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--help' || a === '-h') out.help = true;
    else if (a === '--reindex') out.reindex = true;
    else if (a === '--validate') out.validate = true;
    else if (a === '--d') out.d = argv[++i];
    else if (a === '--pack') out.pack = argv[++i];
    else if (a === '--query') out.query = argv[++i];
    else if (a === '--out') out.out = argv[++i];
    else if (a === '--root') {
      out.root = path.resolve(argv[++i]);
      out.rootGiven = true;
    }
    else if (a === '--factory') out.factory = path.resolve(argv[++i]);
    else if (a === '--max-chunks') {
      out.maxChunks = Number(argv[++i]);
      out.maxChunksGiven = true;
    }
  }
  if (!out.factory) {
    const cand = path.join(out.root, 'witness-done');
    out.factory = fs.existsSync(cand) ? cand : path.resolve(__dirname, '../..');
  }
  if (!out.rootGiven) out.root = resolveProjectRoot(out.root, out.factory);
  return out;
}

function help() {
  console.log(`Usage:
  sp-retrieve.mjs --reindex [--root .]
  sp-retrieve.mjs --d D03 --validate [--pack P03]
  sp-retrieve.mjs --query "auth jwt" --out OUTPUT/context/packs/P-draft.md
`);
}

function outputDir(root, factory) {
  // Корень канона: индекс/паки не пишутся в OUTPUT репозитория (DEC-033).
  const isCanon =
    path.resolve(root) === path.resolve(factory) &&
    fs.existsSync(path.join(factory, 'PIPELINE', '00_bootstrap.md')) &&
    fs.existsSync(path.join(factory, 'catalogs')) &&
    !fs.existsSync(path.join(factory, 'OUTPUT', 'MANIFEST.md'));
  if (isCanon) return path.join(factory, '.witness-done-work');
  // OUTPUT проекта важнее OUTPUT того каталога, откуда запущен CLI (DEC-033).
  const b = path.join(root, 'witness-done', 'OUTPUT');
  const a = path.join(factory, 'OUTPUT');
  if (fs.existsSync(b)) return b;
  if (fs.existsSync(a)) return a;
  return a;
}

function findSpecStateDir(root, factory) {
  const cands = [
    path.join(root, 'spec-state'),
    path.join(factory, 'spec-state'),
    path.join(root, 'witness-done', 'spec-state'),
  ];
  for (const c of cands) {
    if (fs.existsSync(c)) return c;
  }
  return path.join(root, 'spec-state');
}

function walkFiles(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walkFiles(p, acc);
    else if (/\.(md|ya?ml|json)$/i.test(ent.name)) acc.push(p);
  }
  return acc;
}

const DENY_RE = /(\.env|secrets?\/|OUT_OF_SCOPE|node_modules|\.git\/)/i;

function reindex(outRoot, args) {
  const ctx = path.join(outRoot, 'context');
  fs.mkdirSync(ctx, { recursive: true });
  const sources = ['docs', 'specs', 'security', 'roadmaps', 'prompts'].map((s) =>
    path.join(outRoot, s),
  );
  const rows = [];
  let n = 0;
  for (const src of sources) {
    for (const file of walkFiles(src)) {
      const rel = path.relative(outRoot, file).replace(/\\/g, '/');
      if (DENY_RE.test(rel)) continue;
      n += 1;
      const id = `c${String(n).padStart(3, '0')}`;
      const tag = rel.split('/')[0];
      rows.push(`| ${id} | \`OUTPUT/${rel}\` | (file) | ${tag} | — |`);
    }
  }

  // Scan spec-state (baseline and active changes)
  const specDir = findSpecStateDir(args.root, args.factory);
  const baselineDir = path.join(specDir, 'baseline');
  if (fs.existsSync(baselineDir)) {
    for (const file of walkFiles(baselineDir)) {
      const rel = path.relative(specDir, file).replace(/\\/g, '/');
      if (DENY_RE.test(rel)) continue;
      n += 1;
      const id = `c${String(n).padStart(3, '0')}`;
      const domain = rel.split('/')[1] || 'domain';
      rows.push(`| ${id} | \`spec-state/${rel}\` | (spec) | baseline-spec | ${domain} |`);
    }
  }

  const changesDir = path.join(specDir, 'changes');
  if (fs.existsSync(changesDir)) {
    for (const file of walkFiles(changesDir)) {
      const rel = path.relative(specDir, file).replace(/\\/g, '/');
      if (DENY_RE.test(rel)) continue;
      n += 1;
      const id = `c${String(n).padStart(3, '0')}`;
      const changeId = rel.split('/')[1] || 'change';
      rows.push(`| ${id} | \`spec-state/${rel}\` | (delta) | change-delta | ${changeId} |`);
    }
  }

  const body = `# Context Index

> Auto-generated by sp-retrieve --reindex

## Chunks

| chunk_id | path | якорь / заголовок | tags | module |
|----------|------|-------------------|------|--------|
${rows.join('\n') || '| — | — | — | — | — |'}

## Stats

- total_chunks: ${n}
- updated: ${new Date().toISOString().slice(0, 10)}
`;
  const dest = path.join(ctx, 'index.md');
  fs.writeFileSync(dest, body, 'utf8');
  console.log(`Wrote ${dest} (${n} chunks)`);
  return 0;
}

function readPromptForD(outRoot, d) {
  const dir = path.join(outRoot, 'prompts');
  if (!fs.existsSync(dir)) return null;
  const hit = fs.readdirSync(dir).find((f) => f.startsWith(`${d}_`) || f.startsWith(d));
  if (!hit) return null;
  return { path: path.join(dir, hit), text: fs.readFileSync(path.join(dir, hit), 'utf8') };
}

function extractAnchors(text) {
  const anchors = new Set();
  const cons = text.match(/## CONSUMES([\s\S]*?)(?:\n## |$)/);
  // Без CONSUMES смотрим тело задания, но без блоков, которые описывают сам pack и его выход:
  // иначе pack_path попадает в must-hit и проверка доказывает сама себя.
  let block = cons
    ? cons[1]
    : text
        .replace(/## CONTEXT_PACK([\s\S]*?)(?:\n## |$)/, '')
        .replace(/## PRODUCES([\s\S]*?)(?:\n## |$)/, '')
        .replace(/## VERIFICATION_TAX([\s\S]*?)(?:\n## |$)/, '');
  for (const m of block.matchAll(/`(GET|POST|PUT|PATCH|DELETE)\s+[^`]+`/gi)) {
    anchors.add(m[0].replace(/`/g, ''));
  }
  for (const m of block.matchAll(/(?:OUTPUT|spec-state)\/[^\s`)|]+/g)) {
    const p = m[0].replace(/[.,;:]+$/, '');
    // Артефакты контекста и акты — не поставка задания, их нельзя требовать как must-hit.
    if (/^OUTPUT\/(context|evidence)\//.test(p)) continue;
    anchors.add(p);
  }
  return [...anchors];
}

function packPath(outRoot, packId, d) {
  const packs = path.join(outRoot, 'context', 'packs');
  if (packId) return path.join(packs, `${packId}.md`);
  if (d) {
    const num = d.replace(/\D/g, '') || '00';
    return path.join(packs, `P${num}.md`);
  }
  return path.join(packs, 'P-draft.md');
}

function validatePack(outRoot, args) {
  const prompt = args.d ? readPromptForD(outRoot, args.d) : null;
  const anchors = prompt ? extractAnchors(prompt.text) : [];
  const pPath = packPath(outRoot, args.pack, args.d);

  // Validation never creates a pack: a missing pack is a hard failure.
  if (!fs.existsSync(pPath)) {
    const rel = path.relative(outRoot, pPath).replace(/\\/g, '/');
    const error = `Context pack not found: OUTPUT/${rel} — create it explicitly before validation`;
    console.error(error);
    console.log(
      JSON.stringify({ ok: false, must_hit_ok: false, missing_pack: rel, error }, null, 2),
    );
    return 2;
  }
  const packText = fs.readFileSync(pPath, 'utf8');

  const chunkPaths = [...packText.matchAll(/`?((?:OUTPUT|spec-state)\/[^`|\s]+)`?/g)].map((m) => m[1]);
  const unique = [...new Set(chunkPaths)];
  const dropped = unique.filter((p) => DENY_RE.test(p));
  const kept = unique.filter((p) => !DENY_RE.test(p));
  const specDir = findSpecStateDir(args.root, args.factory);
  const missing = [];
  for (const rel of kept) {
    let abs;
    if (rel.startsWith('OUTPUT/')) {
      abs = path.join(outRoot, rel.replace(/^OUTPUT\//, ''));
    } else if (rel.startsWith('spec-state/')) {
      abs = path.join(specDir, rel.replace(/^spec-state\//, ''));
    }
    if (!abs || !fs.existsSync(abs)) missing.push(rel);
  }

  const mustHitOk = anchors.length === 0
    ? true
    : anchors.every((a) => packText.includes(a) || kept.includes(a));

  // Meta пака: заявленный max_chunks не может быть больше лимита канона и меньше числа чанков.
  const metaRaw = (packText.match(/\|\s*max_chunks\s*\|\s*([^|\n]+)\|/i) || [])[1] || '';
  const metaMax = parseInt(metaRaw.replace(/[^0-9]/g, ''), 10);
  const metaDeclared = Number.isFinite(metaMax);
  const metaOk = metaDeclared && metaMax >= 1 && metaMax <= CANON_MAX_CHUNKS && kept.length <= metaMax;

  const over = kept.length > args.maxChunks;
  const overCanon = kept.length > CANON_MAX_CHUNKS;
  const mustHitPaths = packText
    .split('\n')
    .filter((l) => /^\|/.test(l) && /\|\s*yes\s*\|\s*$/i.test(l))
    .map((l) => (l.match(/`((?:OUTPUT|spec-state)\/[^`]+)`/) || [])[1])
    .filter(Boolean);
  const missingMustHit = mustHitPaths.filter((p) => missing.includes(p));
  const mustHitSection = /##\s*Must-hit anchors/i.test(packText);
  const mustHitRowsOk = mustHitPaths.length > 0 && missingMustHit.length === 0;
  const validation = {
    ok: Boolean(
      mustHitOk && mustHitRowsOk && mustHitSection && missing.length === 0 && !over && !overCanon && metaOk,
    ),
    must_hit_ok: mustHitOk && mustHitRowsOk,
    must_hit_section: mustHitSection,
    must_hit_paths: mustHitPaths,
    missing_must_hit: missingMustHit,
    anchors,
    chunks: kept.slice(0, args.maxChunks),
    dropped,
    missing,
    over_max_chunks: over || overCanon,
    max_chunks: args.maxChunks,
    canon_max_chunks: CANON_MAX_CHUNKS,
    meta_max_chunks: metaDeclared ? metaMax : null,
    meta_max_chunks_ok: metaOk,
    timestamp: new Date().toISOString(),
  };

  const vPath = pPath.replace(/\.md$/, '.validation.json');
  fs.writeFileSync(vPath, JSON.stringify(validation, null, 2), 'utf8');
  console.log(JSON.stringify(validation, null, 2));
  console.log(`Wrote ${vPath}`);
  return validation.ok ? 0 : 2;
}

function draftFromQuery(outRoot, query, outFile, maxChunks) {
  const indexPath = path.join(outRoot, 'context', 'index.md');
  if (!fs.existsSync(indexPath)) {
    console.error('No index — run --reindex first');
    return 1;
  }
  const idx = fs.readFileSync(indexPath, 'utf8');
  const q = query.toLowerCase().split(/\s+/).filter(Boolean);
  const lines = idx.split('\n').filter((l) => l.startsWith('| c'));
  const scored = lines
    .map((l) => {
      const low = l.toLowerCase();
      const score = q.reduce((s, t) => s + (low.includes(t) ? 1 : 0), 0);
      const pathMatch = l.match(/`((?:OUTPUT|spec-state)\/[^`]+)`/);
      return { score, path: pathMatch ? pathMatch[1] : null, line: l };
    })
    .filter((x) => x.path && x.score > 0 && !DENY_RE.test(x.path))
    .sort((a, b) => b.score - a.score)
    .slice(0, maxChunks);

  const dest = outFile || path.join(outRoot, 'context', 'packs', 'P-draft.md');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const body = `# Context Pack draft

## Meta
| retrieve_query | ${query} |
| max_chunks | ${maxChunks} |

## Chunks (keyword rank — approve via --validate)
| # | path | score | must_hit |
|---|------|-------|----------|
${scored.map((s, i) => `| ${i + 1} | \`${s.path}\` | ${s.score} | no |`).join('\n')}

> Embedding re-rank optional later; must_hit required before approve.
`;
  fs.writeFileSync(dest, body, 'utf8');
  console.log(`Wrote draft ${dest} (${scored.length} candidates)`);
  return 0;
}

/** Лимит канона: ≤12 чанков на pack (catalogs/context-rag.md). Флаг не может его поднять. */
const CANON_MAX_CHUNKS = 12;

function maxChunksError(args) {
  if (!Number.isFinite(args.maxChunks) || args.maxChunks < 1) {
    return `--max-chunks: нужно целое число ≥1, получено «${args.maxChunks}»`;
  }
  if (args.maxChunks > CANON_MAX_CHUNKS) {
    return `--max-chunks ${args.maxChunks} > ${CANON_MAX_CHUNKS} — лимит канона (catalogs/context-rag.md)`;
  }
  return null;
}

function main() {
  const args = parseArgs(process.argv);
  if (args.help || (!args.reindex && !args.validate && !args.query)) {
    help();
    process.exit(args.help ? 0 : 1);
  }
  const chunksErr = maxChunksError(args);
  if (chunksErr) {
    console.error(chunksErr);
    process.exit(1);
  }
  const outRoot = outputDir(args.root, args.factory);
  if (args.reindex) process.exit(reindex(outRoot, args));
  if (args.query) process.exit(draftFromQuery(outRoot, args.query, args.out, args.maxChunks));
  if (args.validate) process.exit(validatePack(outRoot, args));
}

main();
